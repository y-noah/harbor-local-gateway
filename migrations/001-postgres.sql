CREATE SCHEMA IF NOT EXISTS harbor;
CREATE TABLE IF NOT EXISTS harbor.members(
 id TEXT PRIMARY KEY,name TEXT NOT NULL,quota BIGINT,used BIGINT NOT NULL DEFAULT 0,
 enabled INTEGER NOT NULL DEFAULT 1,created BIGINT NOT NULL,removed_at BIGINT,
 usage_limits TEXT NOT NULL DEFAULT '{"enabled":false,"rules":[]}',usage_limits_version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS harbor.keys(
 id TEXT PRIMARY KEY,member_id TEXT NOT NULL REFERENCES harbor.members(id),digest TEXT UNIQUE NOT NULL,prefix TEXT NOT NULL,
 expires BIGINT,enabled INTEGER NOT NULL DEFAULT 1,created BIGINT NOT NULL,secret_cipher TEXT,allowed_models TEXT,
 model_policy_version BIGINT NOT NULL DEFAULT 0,unmetered BIGINT NOT NULL DEFAULT 0,quota BIGINT,used BIGINT NOT NULL DEFAULT 0,removed_at BIGINT
);
CREATE INDEX IF NOT EXISTS keys_member ON harbor.keys(member_id);
CREATE TABLE IF NOT EXISTS harbor.accounts(
 id TEXT PRIMARY KEY,name TEXT NOT NULL,kind TEXT NOT NULL DEFAULT 'codex',home TEXT NOT NULL,
 enabled INTEGER NOT NULL DEFAULT 1,state TEXT NOT NULL DEFAULT 'unknown',last_used BIGINT NOT NULL DEFAULT 0,last_error TEXT,
 quota_json TEXT,quota_error TEXT,token_budget BIGINT,budget_used BIGINT NOT NULL DEFAULT 0,since_check_tokens BIGINT NOT NULL DEFAULT 0,
 tokens_per_percent DOUBLE PRECISION NOT NULL DEFAULT 10000,quota_calibration TEXT,removed_at BIGINT,
 auth_mode TEXT NOT NULL DEFAULT 'subscription',api_weight DOUBLE PRECISION NOT NULL DEFAULT 0,api_secret_cipher TEXT,api_secret_digest TEXT,
 platform_config TEXT NOT NULL DEFAULT '{}',platform_models TEXT NOT NULL DEFAULT '[]',route_block TEXT,route_epoch BIGINT NOT NULL DEFAULT 0,route_blocked_at BIGINT
);
CREATE TABLE IF NOT EXISTS harbor.sessions(
 id TEXT PRIMARY KEY,member_id TEXT NOT NULL REFERENCES harbor.members(id),account_id TEXT NOT NULL REFERENCES harbor.accounts(id),
 upstream_id TEXT,state TEXT NOT NULL DEFAULT 'new',message_count BIGINT NOT NULL DEFAULT 0,history_digest TEXT NOT NULL DEFAULT '',
 created BIGINT NOT NULL,updated BIGINT NOT NULL,cum_input BIGINT NOT NULL DEFAULT 0,cum_output BIGINT NOT NULL DEFAULT 0,cum_cached BIGINT NOT NULL DEFAULT 0,
 protocol TEXT NOT NULL DEFAULT 'chat',client_key TEXT,client_session_id TEXT,title TEXT,upstream_thread TEXT,
 route_version BIGINT NOT NULL DEFAULT 0,enabled INTEGER NOT NULL DEFAULT 1,nightly_enabled INTEGER NOT NULL DEFAULT 1,nightly_expires BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS session_client ON harbor.sessions(member_id,protocol,client_key) WHERE client_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS session_activity ON harbor.sessions(updated DESC,id DESC);
CREATE TABLE IF NOT EXISTS harbor.pricing_versions(id TEXT PRIMARY KEY,created BIGINT NOT NULL,book TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS harbor.gateway_settings(name TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS harbor.audit(id TEXT PRIMARY KEY,at BIGINT NOT NULL,action TEXT NOT NULL,detail TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS audit_time ON harbor.audit(at DESC,id DESC);
CREATE TABLE IF NOT EXISTS harbor.balance_runs(day TEXT PRIMARY KEY,started BIGINT NOT NULL,ended BIGINT,status TEXT NOT NULL,summary TEXT);
CREATE TABLE IF NOT EXISTS harbor.requests(
 id TEXT PRIMARY KEY,member_id TEXT REFERENCES harbor.members(id),key_id TEXT REFERENCES harbor.keys(id),account_id TEXT REFERENCES harbor.accounts(id),
 started BIGINT NOT NULL,ended BIGINT,status TEXT NOT NULL,ip TEXT NOT NULL,agent TEXT,model TEXT,
 input BIGINT NOT NULL DEFAULT 0,output BIGINT NOT NULL DEFAULT 0,cached BIGINT NOT NULL DEFAULT 0,reserved BIGINT NOT NULL DEFAULT 0,error TEXT,
 tracking_only INTEGER NOT NULL DEFAULT 0,route_version BIGINT,price_version TEXT,billing_model TEXT,manual_cost_atoms TEXT,
 usage_unknown INTEGER NOT NULL DEFAULT 0,phase TEXT,phase_at BIGINT,phase_history TEXT NOT NULL DEFAULT '[]',
 session_id TEXT REFERENCES harbor.sessions(id),predicted BIGINT NOT NULL DEFAULT 10000,
 query_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
 usage_at BIGINT GENERATED ALWAYS AS (COALESCE(ended,started)) STORED,
 business_status TEXT NOT NULL DEFAULT 'unknown',received_at BIGINT,first_event_at BIGINT,first_content_at BIGINT,
 source_channel TEXT,effort TEXT,service_tier TEXT,upstream_request_id TEXT,
 recording_state TEXT NOT NULL DEFAULT 'historical',recording_reason TEXT,
 CHECK(recording_state IN ('historical','disabled','pending','complete','partial','truncated','expired'))
);
CREATE UNIQUE INDEX IF NOT EXISTS request_sequence ON harbor.requests(query_sequence);
CREATE INDEX IF NOT EXISTS request_time ON harbor.requests(usage_at);
CREATE INDEX IF NOT EXISTS request_member_ended ON harbor.requests(member_id,ended);
CREATE INDEX IF NOT EXISTS request_stable_page ON harbor.requests(started DESC,id DESC);
CREATE INDEX IF NOT EXISTS request_member_page ON harbor.requests(member_id,started DESC,id DESC);
CREATE INDEX IF NOT EXISTS request_model_page ON harbor.requests(COALESCE(billing_model,model),started DESC,id DESC);
CREATE INDEX IF NOT EXISTS request_status_page ON harbor.requests(status,started DESC,id DESC);
CREATE INDEX IF NOT EXISTS request_session_page ON harbor.requests(session_id,started DESC,id DESC);
CREATE TABLE IF NOT EXISTS harbor.request_prices(
 request_id TEXT PRIMARY KEY REFERENCES harbor.requests(id) ON DELETE CASCADE,
 state TEXT NOT NULL,model TEXT,model_source TEXT,revision TEXT,
 input_atoms NUMERIC,output_atoms NUMERIC,cached_atoms NUMERIC,adjustment_atoms NUMERIC,total_atoms NUMERIC,
 measured_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS harbor.recordings(
 request_id TEXT PRIMARY KEY REFERENCES harbor.requests(id) ON DELETE CASCADE,
 next_sequence BIGINT NOT NULL DEFAULT 1,persisted_sequence BIGINT NOT NULL DEFAULT 0,
 turn_state TEXT NOT NULL DEFAULT 'uncertain',expires_at BIGINT NOT NULL,
 bytes BIGINT NOT NULL DEFAULT 0,updated BIGINT NOT NULL,preview_cipher BYTEA,
 CHECK(turn_state IN ('known','uncertain'))
);
CREATE INDEX IF NOT EXISTS recording_expiration ON harbor.recordings(expires_at,request_id);
CREATE TABLE IF NOT EXISTS harbor.conversation_events(
 request_id TEXT NOT NULL REFERENCES harbor.recordings(request_id) ON DELETE CASCADE,
 sequence BIGINT NOT NULL,source_key TEXT NOT NULL,kind TEXT NOT NULL,provenance TEXT NOT NULL,
 created BIGINT NOT NULL,content_cipher BYTEA NOT NULL,search_terms BYTEA[] NOT NULL DEFAULT '{}',
 PRIMARY KEY(request_id,sequence),UNIQUE(request_id,source_key),
 CHECK(kind IN ('user','assistant','tool_call','tool_result','attachment','boundary')),
 CHECK(provenance IN ('client','upstream','gateway'))
);
CREATE INDEX IF NOT EXISTS recording_search ON harbor.conversation_events USING GIN(search_terms);
CREATE TABLE IF NOT EXISTS harbor.background_jobs(
 id TEXT PRIMARY KEY,kind TEXT NOT NULL,target TEXT,payload JSONB NOT NULL DEFAULT '{}',
 status TEXT NOT NULL DEFAULT 'pending',attempts INTEGER NOT NULL DEFAULT 0,
 available_at BIGINT NOT NULL,claimed_at BIGINT,lease_until BIGINT,created BIGINT NOT NULL,updated BIGINT NOT NULL,
 progress JSONB NOT NULL DEFAULT '{}',result JSONB,error_code TEXT,expires_at BIGINT,
 CHECK(status IN ('pending','running','completed','failed','cancelled'))
);
CREATE INDEX IF NOT EXISTS jobs_available ON harbor.background_jobs(kind,available_at,id) WHERE status='pending';
